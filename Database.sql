CREATE TABLE NCC (
    MaNCC VARCHAR(6) NOT NULL,
    TenNCC VARCHAR(50),
    Diachi VARCHAR(100),
    SDT VARCHAR(10),
    PRIMARY KEY (MaNCC)
);

CREATE TABLE SANPHAM (
    MaSP VARCHAR(6) NOT NULL,
    TenSP VARCHAR(50),
    Giaban INT,
    Soluong INT,
    TenNCC VARCHAR(50),
    DviTinh VARCHAR(6),
    PRIMARY KEY (MaSP)
);

CREATE TABLE khachhang (
    MaKH VARCHAR(6) NOT NULL,
    TenKH VARCHAR(50),
    DiaChi VARCHAR(50),
    SDT VARCHAR(10),
    PRIMARY KEY (MaKH)
);

CREATE TABLE NhanSu (
    MaNS VARCHAR(6) NOT NULL,
    HoTen VARCHAR(50),
    GioLam INT,
    SDT VARCHAR(10),
    Luong DECIMAL(18, 2),
    PRIMARY KEY (MaNS)
);

CREATE TABLE NhanVien (
    MaNv VARCHAR(6) NOT NULL,
    HoTen VARCHAR(50),
    GioLam INT,
    SDT VARCHAR(10),
    Luong DECIMAL(18, 2),
    PRIMARY KEY (MaNv)
);

CREATE TABLE TAIKHOAN (
    MaTK VARCHAR(50) NOT NULL,
    TenTK VARCHAR(50),
    MatKhau VARCHAR(50),
    VaiTro VARCHAR(50),
    PRIMARY KEY (MaTK)
);

CREATE TABLE HOADON (
    MaHD VARCHAR(6) NOT NULL,
    Ngaylap DATE,
    MaKH VARCHAR(6),
    MaNv VARCHAR(6),
    PRIMARY KEY (MaHD),
    CONSTRAINT FK_HOADON_khachhang FOREIGN KEY (MaKH) REFERENCES khachhang(MaKH),
    CONSTRAINT FK_HOADON_NhanVien FOREIGN KEY (MaNv) REFERENCES NhanVien(MaNv)
);

CREATE TABLE CTHOADON (
    MaHD VARCHAR(6) NOT NULL,
    MaSP VARCHAR(6) NOT NULL,
    TenSP VARCHAR(50),
    SlBan INT,
    GiaBan DECIMAL(18, 2),
    Giamgia FLOAT,
    TongHD DECIMAL(18, 2),
    DviTinh VARCHAR(6),
    PRIMARY KEY (MaHD, MaSP),
    CONSTRAINT FK_CTHOADON_HOADON FOREIGN KEY (MaHD) REFERENCES HOADON(MaHD),
    CONSTRAINT FK_CTHOADON_SANPHAM FOREIGN KEY (MaSP) REFERENCES SANPHAM(MaSP)
);

CREATE TABLE PNHAP (
    MaPN VARCHAR(8) NOT NULL,
    MaNCC VARCHAR(6),
    Ngaynhap DATE,
    PRIMARY KEY (MaPN),
    CONSTRAINT FK_PNHAP_NCC FOREIGN KEY (MaNCC) REFERENCES NCC(MaNCC)
);

CREATE TABLE CTPNHAP (
    MaPN VARCHAR(8) NOT NULL,
    MaSP VARCHAR(6) NOT NULL,
    SlNhap INT,
    Gianhap DECIMAL(18, 2),
    TongGT DECIMAL(18, 2),
    PRIMARY KEY (MaPN, MaSP),
    CONSTRAINT FK_CTPNHAP_PNHAP FOREIGN KEY (MaPN) REFERENCES PNHAP(MaPN),
    CONSTRAINT FK_CTPNHAP_SANPHAM FOREIGN KEY (MaSP) REFERENCES SANPHAM(MaSP)
);

CREATE TABLE TONKHO (
    Namthang DATE NOT NULL,
    MaSP VARCHAR(6) NOT NULL,
    SlBandau INT,
    SlNhap INT,
    SlBan INT,
    SlConlai INT,
    DviTinh VARCHAR(50),
    PRIMARY KEY (Namthang, MaSP),
    CONSTRAINT FK_TONKHO_SANPHAM FOREIGN KEY (MaSP) REFERENCES SANPHAM(MaSP)
);

CREATE TABLE DOANHTHU (
    Thang DATE NOT NULL,
    MaSP VARCHAR(6) NOT NULL,
    Doanhthu DECIMAL(18, 2),
    Loinhuan DECIMAL(18, 2),
    PRIMARY KEY (Thang, MaSP),
    CONSTRAINT FK_DOANHTHU_SANPHAM FOREIGN KEY (MaSP) REFERENCES SANPHAM(MaSP)
);